"""Generate docs/SEBI_RULEBOOK.md from the rules and the verified source registry.

    uv run python -m papertrail.rulebook.catalog_doc > docs/SEBI_RULEBOOK.md

A test checks that the committed file matches, so the docs can never drift from the code.
"""

from __future__ import annotations

from papertrail.models import STANDARD_NOTICES
from papertrail.rulebook.rules import rule_catalog
from papertrail.rulebook.sources import load_sources

_LEVEL_TEXT = {
    "full_text": "Read in full",
    "official_listing": "Title and date confirmed on SEBI's site",
    "quoted_in_sebi_orders": "Wording as quoted in SEBI's own orders",
}


def render() -> str:
    lines = [
        "# The PaperTrail SEBI rulebook",
        "",
        "<!-- Generated by `python -m papertrail.rulebook.catalog_doc`. Do not edit by hand. -->",
        "",
        "PaperTrail compares what finance creators say with official SEBI rules and investor "
        "guidance. This page lists every check it runs and the official source behind each one.",
        "",
        "## Two kinds of flag",
        "",
        "| Label | What it means |",
        "|---|---|",
        "| **Official SEBI rule or guidance** | Comes from a fixed rule that cites a SEBI "
        "document we verified and link to. It describes what was said and what SEBI's material "
        "says. It is **not** a finding that anyone broke a rule. |",
        "| **Potential concern (AI observation)** | Something the AI noticed that may deserve a "
        "closer look. It never names a regulation and is never presented as a violation. |",
        "",
        "Only SEBI or a court can decide whether a rule was broken.",
        "",
        "## Checks",
        "",
    ]
    for rule in rule_catalog():
        lines += [
            f"### {rule['title']}",
            "",
            f"- **What we look for:** {rule['what']}",
            f"- **Why it matters:** {rule['why']}",
            f"- **What you should know:** {rule['takeaway']}",
        ]
        if rule["provision"]:
            lines.append(f"- **Relevant provision:** {rule['provision']}")
        refs = ", ".join(f"[{s['title']}]({s['url']})" for s in rule["sources"])
        lines += [f"- **Official sources:** {refs}", ""]

    lines += [
        "## Official sources",
        "",
        "| Source | Reference | Published | How we verified it | Last checked |",
        "|---|---|---|---|---|",
    ]
    for s in load_sources().values():
        published = s.published_on.isoformat() if s.published_on else "Not stated on page"
        if s.amended_up_to:
            published += f" (amended up to {s.amended_up_to.isoformat()})"
        if s.updated_on:
            published += f" (updated {s.updated_on.isoformat()})"
        lines.append(
            f"| [{s.title}]({s.url}) | {s.reference_number or '-'} | {published} | "
            f"{_LEVEL_TEXT[s.verification_level.value]} | {s.verified_on} |"
        )
    lines += [
        "",
        "## Deliberately not checked",
        "",
        "- **Missing disclaimers.** We have not verified an official requirement that applies to "
        "unregistered creators, so we do not flag its absence.",
        "- **Whether price data was from the last 30 days.** We cannot see the data a creator "
        "used, so the 'education' check is worded conditionally.",
        "",
        "## Always shown with results",
        "",
        *[f"- {n}" for n in STANDARD_NOTICES],
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover
    print(render(), end="")
